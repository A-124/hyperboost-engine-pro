import java.net.URL
import java.security.MessageDigest
import java.util.Locale

data class UpdateInfo(
    val version: String,
    val versionCode: Int,
    val notes: String,
    val apkUrl: String,
    val sha256: String,
    val minimumSupportedVersion: String
)

sealed class CompatibilityResult {
    data object Compatible : CompatibilityResult()
    data class Incompatible(val installedCertSha256: String, val updateCertSha256: String) : CompatibilityResult()
    data object CannotVerify : CompatibilityResult()
}

/** A saved update APK, with a label suitable for the install dialog. */
data class SavedApk(val label: String, val apk: File)

object UpdateManager {
    private const val RELEASE_API = "https://api.github.com/repos/A-124/hyperboost-engine-pro/releases/latest"
    private const val POLICY_URL = "https://raw.githubusercontent.com/A-124/hyperboost-engine-pro/main/update.json"

    suspend fun fetchLatest(): UpdateInfo = withContext(Dispatchers.IO) {
        val release = JSONObject(readUrl(RELEASE_API))
        val version = release.optString("tag_name").removePrefix("v")
        require(version.matches(Regex("""\d+\.\d+\.\d+([-.][A-Za-z0-9.-]+)?"""))) { "The latest release version is invalid." }
        val assets = release.optJSONArray("assets") ?: error("The latest release has no assets.")
        var apkUrl = ""
        var digest = ""
        var checksumUrl = ""
        var manifestUrl = ""

        for (i in 0 until assets.length()) {
            val asset = assets.getJSONObject(i)
            val name = asset.optString("name")
            if (name == "HyperBoost-Engine-Pro-$version.apk" || name == "HyperBoost-Engine-Pro-v$version.apk") {
                apkUrl = asset.optString("browser_download_url")
                digest = asset.optString("digest").removePrefix("sha256:").lowercase()
            } else if (name == "SHA256SUMS.txt") {
                checksumUrl = asset.optString("browser_download_url")
            } else if (name == "version.json") {
                manifestUrl = asset.optString("browser_download_url")
            }
        }

        var versionCode = 0
        var releaseVersion = version
        var notes = release.optString("body", "").trim()
        var minimum = try {
            JSONObject(readUrl(POLICY_URL)).optString("minimumSupportedVersion", "1.0.0")
        } catch (_: Exception) {
            "1.0.0"
        }

        // The version manifest is generated by CI and carries the APK's versionCode. It lets the
        // updater recognise a re-release even when the version name did not change.
        if (manifestUrl.isNotBlank()) {
            try {
                val manifest = JSONObject(readUrl(manifestUrl))
                val code = manifest.optInt("versionCode", 0)
                val name = manifest.optString("versionName", version)
                val manifestApkUrl = manifest.optString("apkUrl", "")
                val manifestSha = manifest.optString("sha256", "").lowercase()
                val manifestNotes = manifest.optString("notes", "").trim()
                val manifestMinimum = manifest.optString("minimumSupportedVersion", "").trim()

                if (code > 0) versionCode = code
                if (name.matches(Regex("""\d+\.\d+\.\d+([-.][A-Za-z0-9.-]+)?"""))) releaseVersion = name
                if (manifestApkUrl.startsWith("https://github.com/")) apkUrl = manifestApkUrl
                if (manifestSha.matches(Regex("[a-f0-9]{64}"))) digest = manifestSha
                if (manifestNotes.isNotBlank()) notes = manifestNotes
                if (manifestMinimum.isNotBlank()) minimum = manifestMinimum
            } catch (_: Exception) {
                // Older releases have no version.json; the GitHub API fields remain the fallback.
            }
        }

        // Fallback: If GitHub API asset metadata did not include SHA-256 digest, parse SHA256SUMS.txt
        if (!digest.matches(Regex("[a-f0-9]{64}")) && checksumUrl.isNotBlank()) {
            try {
                val sums = readUrl(checksumUrl)
                val targetApkName = "HyperBoost-Engine-Pro-$version.apk"
                val line = sums.lines().firstOrNull { it.contains(targetApkName) }
                if (line != null) {
                    val parsedHash = line.trim().split(Regex("""\s+""")).firstOrNull().orEmpty().lowercase()
                    if (parsedHash.matches(Regex("[a-f0-9]{64}"))) {
                        digest = parsedHash
                    }
                }
            } catch (_: Exception) {
                // Ignore fallback parse error; validation below will handle invalid digest
            }
        }

        require(apkUrl.startsWith("https://github.com/") && digest.matches(Regex("[a-f0-9]{64}"))) {
            "The latest release is missing its APK or SHA-256 digest."
        }
        UpdateInfo(releaseVersion, versionCode, notes, apkUrl, digest, minimum)
    }

    /** Prefer the APK versionCode; fall back to versionName for older releases without a manifest. */
    fun isNewer(installedCode: Long, installedVersion: String, update: UpdateInfo): Boolean =
        if (update.versionCode > 0) {
            update.versionCode.toLong() > installedCode
        } else {
            compareVersions(update.version, installedVersion) > 0
        }

    fun compareVersions(left: String, right: String): Int {
        fun parts(v: String) = v.removePrefix("v").substringBefore('-').split('.').map { it.toIntOrNull() ?: 0 }
        val a = parts(left); val b = parts(right)
        for (i in 0 until maxOf(a.size, b.size)) {
            val diff = a.getOrElse(i) { 0 }.compareTo(b.getOrElse(i) { 0 })
            if (diff != 0) return diff
        }
        return when {
            left.contains('-') && !right.contains('-') -> -1
            !left.contains('-') && right.contains('-') -> 1
            else -> 0
        }
    }

    /**
     * Downloads the APK while computing SHA-256 checksum on the fly to avoid out-of-memory errors.
     * Reports download progress if [onProgress] callback is supplied.
     */
    suspend fun downloadAndInstall(
        context: Context,
        info: UpdateInfo,
        onProgress: ((bytesDownloaded: Long, totalBytes: Long, percent: Int) -> Unit)? = null
    ): File = withContext(Dispatchers.IO) {
        val dir = File(context.cacheDir, "updates").apply { mkdirs() }
        // Clean up previously cached APKs to free storage
        dir.listFiles()?.forEach { file ->
            if (file.isFile && file.name.endsWith(".apk")) {
                file.delete()
            }
        }

        val apk = File(dir, "HyperBoost-Engine-Pro-${info.version}.apk")
        val connection = (URL(info.apkUrl).openConnection() as HttpURLConnection).apply {
            connectTimeout = 15000
            readTimeout = 120000
            instanceFollowRedirects = true
            setRequestProperty("User-Agent", "HyperBoost-Engine-Pro")
        }

        val totalBytes = connection.contentLengthLong
        val digest = MessageDigest.getInstance("SHA-256")
        var bytesDownloaded = 0L
        val buffer = ByteArray(8192)

        connection.inputStream.use { input ->
            FileOutputStream(apk).use { output ->
                var read: Int
                var lastProgressUpdate = 0L
                while (input.read(buffer).also { read = it } != -1) {
                    output.write(buffer, 0, read)
                    digest.update(buffer, 0, read)
                    bytesDownloaded += read

                    if (onProgress != null && totalBytes > 0) {
                        val now = System.currentTimeMillis()
                        if (now - lastProgressUpdate > 100 || bytesDownloaded == totalBytes) {
                            lastProgressUpdate = now
                            val percent = ((bytesDownloaded * 100) / totalBytes).toInt()
                            withContext(Dispatchers.Main) {
                                // A UI-only failure must never abort a verified download.
                                runCatching { onProgress(bytesDownloaded, totalBytes, percent) }
                            }
                        }
                    }
                }
            }
        }

        val actual = digest.digest().joinToString("") { "%02x".format(it) }
        if (!actual.equals(info.sha256, true)) {
            apk.delete()
            error("APK checksum verification failed. The file was not installed.")
        }
        apk
    }

    /**
     * Keeps the literal percent sign in the progress text from being parsed as a format flag.
     * Without the escaped `%%`, Java throws `IllegalFormatFlagsException: Flags = '('` on the
     * first progress tick and aborts the download before the installer can open.
     */
    internal fun formatDownloadProgress(percent: Int, downloadedBytes: Long, totalBytes: Long): String =
        String.format(
            Locale.US,
            "Downloading... %d%% (%.1f MB / %.1f MB)",
            percent,
            downloadedBytes / (1024.0 * 1024.0),
            totalBytes / (1024.0 * 1024.0)
        )

    /**
     * Checks if the downloaded APK is signed with the same certificate as the installed app.
     * Prevents Android's "App not installed as package conflicts with an existing package" error.
     */
    fun checkSignatureCompatibility(context: Context, apkFile: File): CompatibilityResult {
        return try {
            val pm = context.packageManager
            val archiveInfo = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
                pm.getPackageArchiveInfo(apkFile.absolutePath, PackageManager.GET_SIGNING_CERTIFICATES)
            } else {
                @Suppress("DEPRECATION")
                pm.getPackageArchiveInfo(apkFile.absolutePath, PackageManager.GET_SIGNATURES)
            } ?: return CompatibilityResult.CannotVerify

            val installedInfo = try {
                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
                    pm.getPackageInfo(context.packageName, PackageManager.GET_SIGNING_CERTIFICATES)
                } else {
                    @Suppress("DEPRECATION")
                    pm.getPackageInfo(context.packageName, PackageManager.GET_SIGNATURES)
                }
            } catch (_: Exception) {
                return CompatibilityResult.Compatible
            }

            fun sha256Hex(bytes: ByteArray): String {
                return MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
            }

            val installedSignatures = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
                installedInfo.signingInfo?.apkContentsSigners?.map { sha256Hex(it.toByteArray()) }
            } else {
                @Suppress("DEPRECATION")
                installedInfo.signatures?.map { sha256Hex(it.toByteArray()) }
            } ?: emptyList()

            val updateSignatures = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
                archiveInfo.signingInfo?.apkContentsSigners?.map { sha256Hex(it.toByteArray()) }
            } else {
                @Suppress("DEPRECATION")
                archiveInfo.signatures?.map { sha256Hex(it.toByteArray()) }
            } ?: emptyList()

            if (installedSignatures.isNotEmpty() && updateSignatures.isNotEmpty()) {
                val matches = installedSignatures.any { updateSignatures.contains(it) }
                if (!matches) {
                    return CompatibilityResult.Incompatible(
                        installedCertSha256 = installedSignatures.firstOrNull() ?: "",
                        updateCertSha256 = updateSignatures.firstOrNull() ?: ""
                    )
                }
            }
            CompatibilityResult.Compatible
        } catch (_: Exception) {
            CompatibilityResult.CannotVerify
        }
    }

    /**
     * Opens Android's system package installer with a granted content URI. This is the
     * compatible path on OEM builds; PackageInstaller sessions are not used because some
     * installers reject them with opaque errors.
     */
    fun launchInstallIntent(context: Context, apk: File) {
        require(apk.isFile && apk.length() > 0L) { "The downloaded update APK is missing or empty." }

        val uri = FileProvider.getUriForFile(context, "${context.packageName}.updates", apk)
        val grant = Intent.FLAG_GRANT_READ_URI_PERMISSION or Intent.FLAG_ACTIVITY_NEW_TASK
        val view = Intent(Intent.ACTION_VIEW).apply {
            setDataAndType(uri, "application/vnd.android.package-archive")
            addFlags(grant)
            clipData = ClipData.newRawUri("HyperBoost update", uri)
        }
        try {
            context.startActivity(view)
            return
        } catch (_: ActivityNotFoundException) {
            // Some older installers only advertise ACTION_INSTALL_PACKAGE.
        }

        val legacy = Intent(Intent.ACTION_INSTALL_PACKAGE).apply {
            data = uri
            addFlags(grant)
            clipData = ClipData.newRawUri("HyperBoost update", uri)
        }
        try {
            context.startActivity(legacy)
        } catch (error: ActivityNotFoundException) {
            throw IllegalStateException("No system package installer is available on this device.", error)
        }
    }

    /**
     * Saves the APK somewhere the user can find it after uninstalling the current build.
     * The cached APK is still returned for the share fallback.
     */
    fun saveApkToDownloads(context: Context, apk: File, version: String): SavedApk? {
        val fileName = "HyperBoost-Engine-Pro-$version.apk"
        val label = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            saveToMediaStore(context, apk, fileName)
        } else {
            saveToLegacyDownloads(context, apk, fileName)
        }
        return label?.let { SavedApk(it, apk) }
    }

    @RequiresApi(Build.VERSION_CODES.Q)
    private fun saveToMediaStore(context: Context, apk: File, fileName: String): String? {
        val resolver = context.contentResolver
        val values = ContentValues().apply {
            put(MediaStore.MediaColumns.DISPLAY_NAME, fileName)
            put(MediaStore.MediaColumns.MIME_TYPE, "application/vnd.android.package-archive")
            put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
            put(MediaStore.MediaColumns.IS_PENDING, 1)
        }
        val collection = MediaStore.Downloads.getContentUri(MediaStore.VOLUME_EXTERNAL_PRIMARY)
        val uri = runCatching { resolver.insert(collection, values) }.getOrNull() ?: return null

        return runCatching {
            resolver.openOutputStream(uri)?.use { output ->
                apk.inputStream().use { input -> input.copyTo(output) }
            } ?: error("Could not open the Downloads file")
            values.clear()
            values.put(MediaStore.MediaColumns.IS_PENDING, 0)
            resolver.update(uri, values, null, null)
            "Downloads/$fileName"
        }.getOrElse {
            runCatching { resolver.delete(uri, null, null) }
            null
        }
    }

    private fun saveToLegacyDownloads(context: Context, apk: File, fileName: String): String? {
        val publicDownloads = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
        val publicWrite = runCatching {
            publicDownloads.mkdirs()
            apk.copyTo(File(publicDownloads, fileName), overwrite = true)
        }
        if (publicWrite.isSuccess) return "Downloads/$fileName"

        // Old Android versions may not have granted legacy storage. Keep a shareable copy in
        // app-specific external storage instead of claiming it was saved to Downloads.
        val fallbackDir = context.getExternalFilesDir(Environment.DIRECTORY_DOWNLOADS) ?: context.cacheDir
        val fallback = runCatching {
            fallbackDir.mkdirs()
            apk.copyTo(File(fallbackDir, fileName), overwrite = true)
        }
        return if (fallback.isSuccess) "app storage/$fileName" else null
    }

    private fun readUrl(address: String): String {
        val connection = URL(address).openConnection() as HttpURLConnection
        connection.connectTimeout = 12000; connection.readTimeout = 20000
        connection.setRequestProperty("Accept", "application/vnd.github+json")
        connection.setRequestProperty("User-Agent", "HyperBoost-Engine-Pro")
        return try {
            val code = connection.responseCode
            val stream = if (code in 200..299) connection.inputStream else connection.errorStream
            val body = stream?.bufferedReader()?.use { it.readText() }.orEmpty()
            if (code !in 200..299) {
                val apiMessage = runCatching { JSONObject(body).optString("message") }
                    .getOrNull()
                    ?.takeIf { it.isNotBlank() }
                    ?.take(180)
                error("Update server returned HTTP $code" + (apiMessage?.let { ": $it" } ?: "."))
            }
            body
        } finally { connection.disconnect() }
    }
}
